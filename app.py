
import streamlit as st
import pandas as pd
import numpy as np
import joblib
import os

# Page Configuration
st.set_page_config(
    page_title="Stock Exchange Prediction",
    page_icon="📈",
    layout="wide"
)

# Load Model
@st.cache_resource
def load_model():
    model = joblib.load("stock_random_forest.pkl")
    features = joblib.load("feature_columns.pkl")
    return model, features

st.title("📈 Stock Exchange Price Prediction")
st.write(
    "Predict stock closing prices using a Random Forest "
    "Machine Learning model."
)

try:
    model, features = load_model()

    st.success("Random Forest model loaded successfully!")

    st.subheader("Enter Stock Information")

    # Create input fields for each model feature
    input_values = {}

    col1, col2 = st.columns(2)

    for i, feature in enumerate(features):
        with (col1 if i % 2 == 0 else col2):
            input_values[feature] = st.number_input(
                f"{feature}",
                value=0.0,
                format="%.4f"
            )

    if st.button("Predict Closing Price", type="primary"):

        input_df = pd.DataFrame(
            [input_values],
            columns=features
        )

        prediction = model.predict(input_df)[0]

        st.subheader("Prediction Result")
        st.metric(
            label="Predicted Closing Price",
            value=f"{prediction:,.2f}"
        )

        st.info(
            "This prediction is generated by a machine learning "
            "model and is not a guarantee of future market prices."
        )

except FileNotFoundError:
    st.error(
        "Model files not found. Upload stock_random_forest.pkl "
        "and feature_columns.pkl to the same GitHub repository "
        "as app.py."
    )

except Exception as e:
    st.error(f"An error occurred: {e}")
